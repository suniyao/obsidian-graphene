const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const vm = require('node:vm');
const output = buildSync({ stdin: { contents: `export * from './src/ui/GraphLayout'; export {DEFAULT_SETTINGS} from './src/types'; export {forceSimulation} from 'd3';`, resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'cjs', write: false });
const sandbox = { module: {exports: {}}, exports: {}, setTimeout, clearTimeout, setInterval, clearInterval, performance };
vm.runInNewContext(output.outputFiles[0].text, sandbox);
const { prepareLayout, configureLayout, DEFAULT_SETTINGS, forceSimulation } = sandbox.module.exports;
const makeNode = id => ({id, name: id, path: id, type: 'file'});
const nodes = Array.from({length: 40}, (_, i) => makeNode(String(i)));
const rawLinks = nodes.slice(1).map((node, i) => ({id: String(i), source: nodes[Math.floor(i / 2)].id, target: node.id, type: 'manual-link'}));
const links = prepareLayout(nodes, rawLinks, [], 400, 300);
const sim = forceSimulation([]).stop().velocityDecay(0.35).alphaDecay(0.025);
configureLayout(sim, nodes, links, DEFAULT_SETTINGS, 400, 300, () => true, () => 6);
sim.tick(400);
assert(nodes.every(n => Number.isFinite(n.x) && Number.isFinite(n.y)), 'layout stays finite');
assert(nodes.every(n => Math.hypot(n.vx, n.vy) < 0.1), 'layout settles');
let minDistance = Infinity;
for (let i = 0; i < nodes.length; i++) for (let j = i + 1; j < nodes.length; j++) minDistance = Math.min(minDistance, Math.hypot(nodes[i].x - nodes[j].x, nodes[i].y - nodes[j].y));
assert(minDistance > 18, 'nodes do not overlap');
const radii = nodes.map(n => Math.hypot(n.x - 400, n.y - 300));
assert(Math.max(...radii) - Math.min(...radii) > 50, 'layout has depth rather than a fixed ring');
const refreshed = nodes.map(n => makeNode(n.id));
const refreshedLinks = prepareLayout(refreshed, links, nodes, 400, 300);
assert.equal(refreshed[0].x, nodes[0].x, 'refresh preserves position');
assert.equal(refreshedLinks[0].source, refreshed[0], 'links resolve to current nodes');
for (const node of refreshed) { node.x = 400; node.y = 300; }
configureLayout(sim, refreshed, refreshedLinks, {...DEFAULT_SETTINGS, linkForce: 0, centerForce: 0}, 400, 300, node => node.id !== '0', () => 6);
assert.equal(sim.nodes().length, 39, 'hidden nodes excluded');
const force = sim.force('link');
assert(force.links().every(l => l.source.id !== '0' && l.target.id !== '0'), 'hidden links excluded');
assert(force.links().every(l => force.strength()(l) === 0), 'zero link force respected');
assert.equal(sim.force('x').strength()(refreshed[1]), 0, 'zero center force respected');
sim.alpha(1).tick(400);
assert(sim.nodes().every(n => Number.isFinite(n.x) && Number.isFinite(n.y)), 'coincident nodes separate without invalid positions');
configureLayout(sim, refreshed, refreshedLinks, DEFAULT_SETTINGS, 400, 300, () => false, () => 6);
sim.tick(10);
assert.equal(sim.nodes().length, 0, 'empty search supported');
sim.stop();
console.log('Graph layout checks passed: settling, overlap, depth, refresh, filtering, zero forces, coincident nodes, empty graph.');
